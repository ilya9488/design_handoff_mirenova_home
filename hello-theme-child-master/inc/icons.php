	/**
	 * Inline SVG for a built-in icon.
	 *
	 * @param string $name  Icon name.
	 * @param array  $attrs Extra attributes (class, width, height, stroke-width…).
	 * @return string
	 */
	public static function svg( $name, $attrs = [] ) {
		$all = self::all();
		if ( ! isset( $all[ $name ] ) ) {
			return '';
		}
		$attrs = array_merge(
			[
				'class'           => 'mrn-ico',
				'viewBox'         => '0 0 24 24',
				'fill'            => 'none',
				'stroke'          => 'currentColor',
				'stroke-width'    => '2',
				'stroke-linecap'  => 'round',
				'stroke-linejoin' => 'round',
				'aria-hidden'     => 'true',
				'focusable'       => 'false',
			],
			$attrs
		);
		$out = '<svg';
		foreach ( $attrs as $k => $v ) {
			if ( '' === $v || null === $v ) {
				continue;
			}
			$out .= ' ' . $k . '="' . esc_attr( $v ) . '"';
		}
		return $out . '>' . $all[ $name ] . '</svg>';
	}
